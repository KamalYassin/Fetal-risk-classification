def validate_outputs(results: pd.DataFrame, transitions: pd.DataFrame) -> None:
    """Check completeness before declaring the diagnostic finished."""
    if len(results) != len(RULE_NAMES) * 2:
        raise ValueError("Expected one result row per rule and evaluation design")
    if set(results["rule"]) != set(RULE_NAMES):
        raise ValueError("A label rule is missing from the results")
    cv = results[results["evaluation_design"] == "repeated_5x5_cv"]
    splits = results[results["evaluation_design"] == "30_predefined_splits"]
    if (cv["valid_evaluations"] + cv["invalid_evaluations"] != 25).any():
        raise ValueError("Each rule must account for all 25 repeated-CV folds")
    if (splits["valid_evaluations"] + splits["invalid_evaluations"] != 30).any():
        raise ValueError("Each rule must account for all 30 predefined splits")
    for path in (RESULTS_PATH, TRANSITIONS_PATH, REPORT_PATH):
        if not path.exists() or path.stat().st_size == 0:
            raise ValueError(f"Missing or empty output: {path}")
    if transitions.empty:
        raise ValueError("Transition summary is unexpectedly empty")


def print_terminal_summary(
    results: pd.DataFrame,
    transitions: pd.DataFrame,
    conclusion: str,
) -> None:
    """Print the decision-relevant sensitivity summary."""
    cv = results[results["evaluation_design"] == "repeated_5x5_cv"].set_index("rule")
    print("\nLabel distributions and changes relative to V1")
    for rule_name in RULE_NAMES:
        row = cv.loc[rule_name]
        changed = int(row["patients_changed_from_v1"])
        print(
            f"{rule_name}: Normal={int(row['normal_count'])}, "
            f"Suspicious={int(row['suspicious_count'])}, "
            f"Pathological={int(row['pathological_count'])}; "
            f"changed from V1={changed}"
        )

    print("\nRepeated-CV results")
    for rule_name in RULE_NAMES:
        row = cv.loc[rule_name]
        print(
            f"{rule_name}: Macro F1={row['macro_f1_mean']:.4f}; "
            f"Pathological recall={row['pathological_recall_mean']:.4f}; "
            f"Pathological precision={row['pathological_precision_mean']:.4f}; "
            f"Pathological recall SD={row['pathological_recall_std']:.4f}"
        )

    print(f"\nMain conclusion: {conclusion}")
    print("Output paths")
    for path in (RESULTS_PATH, TRANSITIONS_PATH, REPORT_PATH):
        print(path)


def main() -> None:
    """Run the isolated label-rule sensitivity analysis."""
    refuse_overwrite()
    dataset, feature_columns = load_and_validate_inputs()
    patient_labels = apply_existing_rules(dataset)
    features = dataset[feature_columns]
    transitions = build_transition_summary(patient_labels)
    transitions.to_csv(TRANSITIONS_PATH, index=False)

    summary_rows = []
    reference = patient_labels[REFERENCE_RULE]
    for rule_position, rule_name in enumerate(RULE_NAMES, start=1):
        target = patient_labels[rule_name].to_numpy()
        counts = patient_labels[rule_name].value_counts()
        changed = int((patient_labels[rule_name] != reference).sum())
        print(f"Evaluating rule {rule_position}/{len(RULE_NAMES)}: {rule_name}")

        cv_evaluations = repeated_cv_evaluation(features, target)
        split_evaluations = predefined_split_evaluation(features, target)
        summary_rows.append(
            summarize_evaluations(
                rule_name,
                "repeated_5x5_cv",
                cv_evaluations,
                counts,
                changed,
            )
        )
        summary_rows.append(
            summarize_evaluations(
                rule_name,
                "30_predefined_splits",
                split_evaluations,
                counts,
                changed,
            )
        )

    results = pd.DataFrame(summary_rows)
    results.to_csv(RESULTS_PATH, index=False)
    cv_summary = results[results["evaluation_design"] == "repeated_5x5_cv"]
