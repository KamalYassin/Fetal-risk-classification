"""Focused sensitivity analysis for the four existing CTG label rules.

This diagnostic keeps patients, the finalized 55-feature representation,
preprocessing, classifier settings, and evaluation seeds fixed.  Only the
patient labels generated by the already-defined V1--V4 rules are changed.

Run from the project root:

    python src/experiments/label_sensitivity_analysis.py

The production labels, datasets, saved models, and previous reports are read
only. The script also protects its own outputs from accidental replacement.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from imblearn.over_sampling import SMOTE
from imblearn.pipeline import Pipeline as ImbalancedPipeline
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    f1_score,
    precision_recall_fscore_support,
)
from sklearn.model_selection import RepeatedStratifiedKFold, train_test_split
from sklearn.preprocessing import StandardScaler

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

# Reuse the existing rule functions rather than restating or changing any
# clinical cutoff in this experiment.
from src.data.compare_label_rules import RULES
from src.models import train_models

DATASET_PATH = (
    PROJECT_ROOT / "data" / "processed" / "ml_dataset_final_temporal.csv"
)
RULE_COMPARISON_PATH = (
    PROJECT_ROOT / "data" / "processed" / "label_rule_comparison.csv"
)
OUTPUT_DIR = PROJECT_ROOT / "reports" / "label_sensitivity_analysis"
RESULTS_PATH = OUTPUT_DIR / "label_sensitivity_results.csv"
TRANSITIONS_PATH = OUTPUT_DIR / "label_transition_summary.csv"
REPORT_PATH = OUTPUT_DIR / "label_sensitivity_report.md"

CLASS_ORDER = ["Normal", "Suspicious", "Pathological"]
RULE_NAMES = [name for name, _ in RULES]
REFERENCE_RULE = "V1_current_rule"
OUTCOME_COLUMNS = ["pH", "BE", "BDecf", "Apgar5"]

# Use the evaluation settings from the patient-level diagnostic and final
# comparison experiments.
SPLIT_SEEDS = list(range(30))
CV_SPLITS = 5
CV_REPEATS = 5
CV_RANDOM_STATE = train_models.RANDOM_STATE  # 42
TEST_SIZE = train_models.TEST_SIZE  # 0.20

METRIC_COLUMNS = [
    "accuracy",
    "balanced_accuracy",
    "macro_f1",
    "normal_recall",
    "suspicious_recall",
    "pathological_recall",
    "pathological_precision",
    "pathological_f1",
    "false_pathological_predictions",
]


def refuse_overwrite() -> None:
    """Stop if this experiment's output files already exist."""
    existing = [
        path for path in (RESULTS_PATH, TRANSITIONS_PATH, REPORT_PATH) if path.exists()
    ]
    if existing:
        joined = ", ".join(str(path) for path in existing)
        raise FileExistsError(f"Refusing to overwrite existing output(s): {joined}")
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


def load_and_validate_inputs() -> tuple[pd.DataFrame, list[str]]:
    """Load the finalized representation and validate its schema."""
    for path in (DATASET_PATH, RULE_COMPARISON_PATH):
        if not path.exists():
            raise FileNotFoundError(f"Required input not found: {path}")

    dataset = pd.read_csv(DATASET_PATH, dtype={"record_id": str})
    if len(dataset) != 552 or dataset["record_id"].nunique() != 552:
        raise ValueError("The finalized dataset must contain 552 unique patients")
    required = {"record_id", "label", *OUTCOME_COLUMNS}
    missing = sorted(required.difference(dataset.columns))
    if missing:
        raise ValueError("Final dataset is missing: " + ", ".join(missing))

    # Use the same leakage exclusions as the training code. The final
    # temporal dataset intentionally has no feature_quality_flag column, but it
    # remains in the exclusion set so it could never enter the model if present.
    excluded = {train_models.TARGET_COLUMN, *train_models.LEAKAGE_COLUMNS}
    feature_columns = [column for column in dataset.columns if column not in excluded]
    if len(feature_columns) != 55:
        raise ValueError(
            f"Expected the finalized 55 features, found {len(feature_columns)}"
        )
    non_numeric = dataset[feature_columns].select_dtypes(
        exclude=[np.number]
    ).columns.tolist()
    if non_numeric:
        raise ValueError("Non-numeric model feature(s): " + ", ".join(non_numeric))

    return dataset, feature_columns


def apply_existing_rules(dataset: pd.DataFrame) -> pd.DataFrame:
    """Apply the V1--V4 functions in memory and validate known counts."""
    patient_labels = pd.DataFrame({"record_id": dataset["record_id"]})
    outcome_rows = dataset[OUTCOME_COLUMNS].itertuples(index=False, name=None)
    cached_outcomes = list(outcome_rows)
    for rule_name, rule_function in RULES:
        patient_labels[rule_name] = [
            rule_function(ph, be, bdecf, apgar5)
            for ph, be, bdecf, apgar5 in cached_outcomes
        ]

    # V1 must match the finalized labels for the comparison to remain controlled.
    mismatches = int(
        (patient_labels[REFERENCE_RULE].to_numpy() != dataset["label"].to_numpy()).sum()
    )
    if mismatches:
        raise ValueError(f"V1 differs from the finalized label for {mismatches} patients")

    comparison = pd.read_csv(RULE_COMPARISON_PATH)
    expected = comparison.pivot(index="rule", columns="class", values="count")
    for rule_name in RULE_NAMES:
        actual = patient_labels[rule_name].value_counts()
        for class_name in CLASS_ORDER:
            expected_count = int(expected.loc[rule_name, class_name])
            if int(actual.get(class_name, 0)) != expected_count:
                raise ValueError(
                    f"{rule_name} {class_name} count does not match the existing "
                    "label-rule comparison"
                )
    return patient_labels


def build_pipeline(smote_seed: int) -> ImbalancedPipeline:
    """Build the fixed, fold-local preprocessing and Logistic Regression model."""
    return ImbalancedPipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", StandardScaler()),
            ("smote", SMOTE(random_state=smote_seed)),
            (
                "classifier",
                LogisticRegression(
                    C=1,
                    solver="lbfgs",
                    max_iter=2000,
                    class_weight=None,
                ),
            ),
        ]
    )


def partition_problem(target: np.ndarray, indices: np.ndarray) -> str | None:
    """Explain why a partition cannot preserve all classes or support SMOTE."""
    counts = pd.Series(target[indices]).value_counts()
    missing = [class_name for class_name in CLASS_ORDER if counts.get(class_name, 0) == 0]
    if missing:
        return "missing class(es): " + ", ".join(missing)
    # Default SMOTE uses five neighbours, so every training class needs at
    # least six patients.
    too_small = [
        f"{class_name}={int(counts.get(class_name, 0))}"
        for class_name in CLASS_ORDER
        if counts.get(class_name, 0) < 6
    ]
    if too_small:
        return "insufficient training patients for default SMOTE: " + ", ".join(too_small)
    return None


def evaluate_predictions(target: np.ndarray, predictions: np.ndarray) -> dict:
    """Calculate multiclass and Pathological-focused metrics."""
    precision, recall, class_f1, _ = precision_recall_fscore_support(
        target,
        predictions,
        labels=CLASS_ORDER,
        zero_division=0,
    )
    class_position = {name: position for position, name in enumerate(CLASS_ORDER)}
    pathological = target == "Pathological"
    predicted_pathological = predictions == "Pathological"
    return {
        "accuracy": float(accuracy_score(target, predictions)),
        "balanced_accuracy": float(balanced_accuracy_score(target, predictions)),
        "macro_f1": float(
            f1_score(target, predictions, average="macro", zero_division=0)
        ),
        "normal_recall": float(recall[class_position["Normal"]]),
        "suspicious_recall": float(recall[class_position["Suspicious"]]),
        "pathological_recall": float(recall[class_position["Pathological"]]),
        "pathological_precision": float(precision[class_position["Pathological"]]),
        "pathological_f1": float(class_f1[class_position["Pathological"]]),
        "false_pathological_predictions": int(
            np.sum(~pathological & predicted_pathological)
        ),
    }


def evaluate_partition(
    features: pd.DataFrame,
    target: np.ndarray,
    train_indices: np.ndarray,
    test_indices: np.ndarray,
    smote_seed: int,
    identity: dict,
) -> dict:
    """Fit and score one valid held-out partition, or report why it is invalid."""
    train_issue = partition_problem(target, train_indices)
    test_classes = set(target[test_indices])
    missing_test = [name for name in CLASS_ORDER if name not in test_classes]
    test_issue = (
        "test partition missing class(es): " + ", ".join(missing_test)
        if missing_test
        else None
    )
    issue = train_issue or test_issue
    if issue:
        return {**identity, "valid": False, "invalid_reason": issue}

    pipeline = build_pipeline(smote_seed)
    pipeline.fit(features.iloc[train_indices], target[train_indices])
    predictions = pipeline.predict(features.iloc[test_indices])
    return {
        **identity,
        "valid": True,
        "invalid_reason": "",
        **evaluate_predictions(target[test_indices], predictions),
    }


def repeated_cv_evaluation(features: pd.DataFrame, target: np.ndarray) -> pd.DataFrame:
    """Run repeated five-by-five stratified cross-validation."""
    minimum_class_count = int(pd.Series(target).value_counts().min())
    if minimum_class_count < CV_SPLITS:
        return pd.DataFrame(
            [
                {
                    "fold_number": np.nan,
                    "valid": False,
                    "invalid_reason": (
                        f"smallest class has {minimum_class_count} patients; "
                        f"{CV_SPLITS}-fold stratification is impossible"
                    ),
                }
            ]
        )

    cv = RepeatedStratifiedKFold(
        n_splits=CV_SPLITS,
        n_repeats=CV_REPEATS,
        random_state=CV_RANDOM_STATE,
    )
    rows = []
    for fold_number, (train_indices, test_indices) in enumerate(
        cv.split(np.zeros(len(target)), target), start=1
    ):
        rows.append(
            evaluate_partition(
                features,
                target,
                train_indices,
                test_indices,
                CV_RANDOM_STATE + fold_number,
                {
                    "fold_number": fold_number,
                    "repeat_number": (fold_number - 1) // CV_SPLITS + 1,
                    "fold_within_repeat": (fold_number - 1) % CV_SPLITS + 1,
                },
            )
        )
    return pd.DataFrame(rows)


def predefined_split_evaluation(
    features: pd.DataFrame, target: np.ndarray
) -> pd.DataFrame:
    """Run the same 30 seeded stratified 80/20 patient splits where valid."""
    rows = []
    patient_indices = np.arange(len(target))
    for seed in SPLIT_SEEDS:
        try:
            train_indices, test_indices = train_test_split(
                patient_indices,
                test_size=TEST_SIZE,
                random_state=seed,
                stratify=target,
            )
        except ValueError as error:
            rows.append(
                {
                    "random_seed": seed,
                    "valid": False,
                    "invalid_reason": str(error),
                }
            )
            continue
        rows.append(
            evaluate_partition(
                features,
                target,
                train_indices,
                test_indices,
                seed,
                {"random_seed": seed},
            )
        )
    return pd.DataFrame(rows)


def summarize_evaluations(
    rule_name: str,
    design_name: str,
    evaluations: pd.DataFrame,
    counts: pd.Series,
    changed_from_v1: int,
) -> dict:
    """Create one summary row for a label rule and evaluation design."""
    valid = evaluations[evaluations["valid"]].copy()
    invalid = evaluations[~evaluations["valid"]].copy()
    row = {
        "rule": rule_name,
        "evaluation_design": design_name,
        "normal_count": int(counts.get("Normal", 0)),
        "suspicious_count": int(counts.get("Suspicious", 0)),
        "pathological_count": int(counts.get("Pathological", 0)),
        "patients_changed_from_v1": changed_from_v1,
        "valid_evaluations": len(valid),
        "invalid_evaluations": len(invalid),
        "invalid_reasons": " | ".join(sorted(set(invalid["invalid_reason"].dropna()))),
    }
    for metric in METRIC_COLUMNS:
        values = valid[metric].astype(float) if not valid.empty else pd.Series(dtype=float)
        row[f"{metric}_mean"] = float(values.mean()) if len(values) else np.nan
        row[f"{metric}_std"] = float(values.std(ddof=1)) if len(values) > 1 else np.nan
    row["false_pathological_predictions_total"] = (
        int(valid["false_pathological_predictions"].sum()) if not valid.empty else 0
    )
    return row


def build_transition_summary(patient_labels: pd.DataFrame) -> pd.DataFrame:
    """Count every changed V1 class -> alternative-rule class transition."""
    rows = []
    reference = patient_labels[REFERENCE_RULE]
    for rule_name in RULE_NAMES:
        alternative = patient_labels[rule_name]
        changed = reference != alternative
        total_changed = int(changed.sum())
        transitions = (
            pd.DataFrame(
                {
                    "v1_class": reference[changed],
                    "alternative_class": alternative[changed],
                }
            )
            .value_counts()
            .sort_index()
        )
        if transitions.empty:
            rows.append(
                {
                    "rule": rule_name,
                    "patients_changed_from_v1": 0,
                    "v1_class": "None",
                    "alternative_class": "None",
                    "patient_count": 0,
                }
            )
        else:
            for (v1_class, alternative_class), count in transitions.items():
                rows.append(
                    {
                        "rule": rule_name,
                        "patients_changed_from_v1": total_changed,
                        "v1_class": v1_class,
                        "alternative_class": alternative_class,
                        "patient_count": int(count),
                    }
                )
    return pd.DataFrame(rows)


def sensitivity_conclusion(cv_summary: pd.DataFrame) -> tuple[str, dict]:
    """Give a cautious interpretation of the observed score ranges."""
    macro_range = float(cv_summary["macro_f1_mean"].max() - cv_summary["macro_f1_mean"].min())
    recall_range = float(
        cv_summary["pathological_recall_mean"].max()
        - cv_summary["pathological_recall_mean"].min()
    )
    precision_range = float(
        cv_summary["pathological_precision_mean"].max()
        - cv_summary["pathological_precision_mean"].min()
    )
    recall_sds = cv_summary["pathological_recall_std"]
    instability_persists = bool((recall_sds >= 0.10).all())

    # These bands interpret effect magnitude only; they do not tune a label
    # rule or alter any model.  "Robust" is reserved for small changes in both
    # overall and minority-class results.  A large overall Macro-F1 change, or
    # loss of the shared instability finding, is treated as high sensitivity.
    if macro_range <= 0.05 and recall_range <= 0.15 and precision_range <= 0.15:
        conclusion = "the main modelling conclusions are robust to reasonable label-rule changes"
    elif macro_range > 0.10 or not instability_persists:
        conclusion = "the main modelling conclusions are highly sensitive to label-rule choice"
    else:
        conclusion = "the main modelling conclusions are moderately sensitive to label-rule choice"
    details = {
        "macro_f1_range": macro_range,
        "pathological_recall_range": recall_range,
        "pathological_precision_range": precision_range,
        "instability_persists": instability_persists,
    }
    return conclusion, details


def markdown_table(frame: pd.DataFrame, decimals: int = 3) -> str:
    """Render a small DataFrame without requiring the optional tabulate package."""
    display = frame.copy()
    for column in display.select_dtypes(include=[np.number]).columns:
        display[column] = display[column].map(
            lambda value: "" if pd.isna(value) else f"{value:.{decimals}f}"
        )
    headers = [str(column) for column in display.columns]
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
    ]
    for row in display.astype(str).itertuples(index=False, name=None):
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


